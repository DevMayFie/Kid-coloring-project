export interface PremadeTemplate {
  id: string;
  theme: string;
  childName: string;
  title: string;
  subtitle: string;
  dedication: string;
  difficulty: 'toddler' | 'standard' | 'intricate';
  artStyle: 'classic' | 'kawaii' | 'storybook' | 'retro-cartoon';
  emoji: string;
  category: 'animals' | 'fantasy' | 'space' | 'ocean' | 'adventure' | 'superhero';
  description: string;
  badge: string;
  pageCount: number;
  tags: string[];
  book: ColoringBook;
}

function buildTemplatePage(
  id: string,
  pageNum: number,
  title: string,
  caption: string,
  tip: string,
  prompt: string,
  sceneKey: string,
  label: string
): ColoringPage {
  return {
    id,
    pageNumber: pageNum,
    title,
    storyCaption: caption,
    funFactOrTip: tip,
    prompt,
    imageUrl: createSampleLineArtSvg(sceneKey, label),
    status: 'completed',
    resolution: '2K',
    activityMode: 'standard',
  };
}

